 private void appendToLeaderboard(String text) { 
        try { 
            leaderboardArea.getDocument().insertString( 
                    leaderboardArea.getDocument().getLength(), 
                    text, 
                    null); 
        } catch (Exception e) { 
            e.printStackTrace(); 
        } 
    } 
