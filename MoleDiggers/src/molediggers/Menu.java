    private void loadLeaderboard() { 
        List<String> scores = Leaderboard.getTopScores(); 
 
        leaderboardArea.setText(""); 
 
        appendToLeaderboard("LEADERBOARD\n\n"); 
        appendToLeaderboard("RANK      NAME     SCORE\n"); 
        appendToLeaderboard("-----------------------\n"); 
 
        int rank = 1; 
        for (String s : scores) { 
            String[] parts = s.split(","); 
 
            appendToLeaderboard( 
                    String.format("%-6d %-8s %5s\n", 
                            rank, parts[0], parts[1])); 
 
            rank++; 
        } 
    } 
